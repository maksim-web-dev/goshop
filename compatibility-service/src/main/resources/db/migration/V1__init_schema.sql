CREATE TABLE compatibility_rules (
    id                     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                   VARCHAR(255) NOT NULL UNIQUE,
    source_product_type_id BIGINT       NOT NULL,
    target_product_type_id BIGINT       NOT NULL,
    rule_type              VARCHAR(255) NOT NULL,
    parameters             JSONB,
    severity               VARCHAR(255) NOT NULL,
    enabled                BOOLEAN      NOT NULL,
    version                INTEGER      NOT NULL
);

CREATE TABLE compatibility_checks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    compatible BOOLEAN     NOT NULL,
    checked_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE compatibility_check_products (
    check_id   BIGINT NOT NULL REFERENCES compatibility_checks (id),
    product_id BIGINT NOT NULL
);

CREATE TABLE compatibility_issues (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    check_id     BIGINT       NOT NULL REFERENCES compatibility_checks (id),
    rule_id      BIGINT       NOT NULL REFERENCES compatibility_rules (id),
    severity     VARCHAR(255) NOT NULL,
    message_code VARCHAR(255) NOT NULL
);
