CREATE TABLE prices (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id    BIGINT         NOT NULL,
    store_id      BIGINT,
    amount        NUMERIC(19, 4) NOT NULL,
    currency_code VARCHAR(3)     NOT NULL,
    valid_from    TIMESTAMPTZ    NOT NULL,
    valid_to      TIMESTAMPTZ,
    updated_at    TIMESTAMPTZ    NOT NULL
);

CREATE INDEX idx_prices_product_id    ON prices (product_id);
CREATE INDEX idx_prices_store_id      ON prices (store_id);
CREATE INDEX idx_prices_currency_code ON prices (currency_code);
CREATE INDEX idx_prices_valid_to      ON prices (valid_to);

CREATE TABLE price_history (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price_id   BIGINT         NOT NULL REFERENCES prices (id),
    old_amount NUMERIC(19, 4) NOT NULL,
    new_amount NUMERIC(19, 4) NOT NULL,
    changed_at TIMESTAMPTZ    NOT NULL
);

CREATE TABLE exchange_rates (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_currency VARCHAR(3)     NOT NULL,
    to_currency   VARCHAR(3)     NOT NULL,
    rate          NUMERIC(19, 8) NOT NULL,
    effective_at  TIMESTAMPTZ    NOT NULL
);

CREATE TABLE discounts (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id       BIGINT         NOT NULL,
    product_id     BIGINT,
    discount_type  VARCHAR(255)   NOT NULL,
    discount_value NUMERIC(19, 4) NOT NULL,
    starts_at      TIMESTAMPTZ    NOT NULL,
    ends_at        TIMESTAMPTZ,
    status         VARCHAR(255)   NOT NULL
);

CREATE INDEX idx_discounts_store_id   ON discounts (store_id);
CREATE INDEX idx_discounts_product_id ON discounts (product_id);
CREATE INDEX idx_discounts_status     ON discounts (status);
CREATE INDEX idx_discounts_starts_at  ON discounts (starts_at);
