CREATE TABLE search_documents (
    product_id      BIGINT       PRIMARY KEY,
    sku             VARCHAR(64)  NOT NULL,
    name            VARCHAR(512) NOT NULL,
    brand           VARCHAR(128) NOT NULL,
    category_id     BIGINT       NOT NULL,
    searchable_text TSVECTOR,
    localized_names JSONB,
    attributes      JSONB,
    status          VARCHAR(32)  NOT NULL,
    indexed_at      TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_search_documents_fts   ON search_documents USING GIN (searchable_text);
CREATE INDEX idx_search_documents_brand ON search_documents (brand);
CREATE INDEX idx_search_documents_cat   ON search_documents (category_id);

CREATE TABLE search_index_jobs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT       NOT NULL,
    operation  VARCHAR(255) NOT NULL,
    status     VARCHAR(255) NOT NULL,
    attempts   INTEGER      NOT NULL,
    created_at TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_search_index_jobs_product_id ON search_index_jobs (product_id);
CREATE INDEX idx_search_index_jobs_status     ON search_index_jobs (status);
