CREATE TABLE stores (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name             VARCHAR(255) NOT NULL,
    domain           VARCHAR(255) NOT NULL UNIQUE,
    country_code     VARCHAR(2)   NOT NULL,
    default_language VARCHAR(10)  NOT NULL,
    default_currency VARCHAR(3)   NOT NULL,
    status           VARCHAR(255) NOT NULL,
    created_at       TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_stores_status ON stores (status);

CREATE TABLE store_api_keys (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id     BIGINT       NOT NULL REFERENCES stores (id),
    key_hash     VARCHAR(255) NOT NULL,
    key_prefix   VARCHAR(16)  NOT NULL,
    status       VARCHAR(255) NOT NULL,
    created_at   TIMESTAMPTZ  NOT NULL,
    expires_at   TIMESTAMPTZ,
    last_used_at TIMESTAMPTZ
);

CREATE INDEX idx_store_api_keys_store_id          ON store_api_keys (store_id);
CREATE INDEX idx_store_api_keys_key_prefix_status ON store_api_keys (key_prefix, status);

CREATE TABLE store_settings (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id            BIGINT   NOT NULL UNIQUE REFERENCES stores (id),
    requests_per_second INTEGER  NOT NULL,
    burst_limit         INTEGER  NOT NULL
);

CREATE TABLE store_allowed_languages (
    store_settings_id BIGINT      NOT NULL REFERENCES store_settings (id),
    language_code     VARCHAR(10) NOT NULL
);

CREATE TABLE store_webhooks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id   BIGINT       NOT NULL REFERENCES stores (id),
    url        VARCHAR(255) NOT NULL,
    secret_ref VARCHAR(255) NOT NULL,
    enabled    BOOLEAN      NOT NULL
);

CREATE INDEX idx_store_webhooks_store_id ON store_webhooks (store_id);

CREATE TABLE store_webhook_event_types (
    webhook_id BIGINT       NOT NULL REFERENCES store_webhooks (id),
    event_type VARCHAR(255) NOT NULL
);
