CREATE TABLE brands (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(255) NOT NULL UNIQUE,
    website_url VARCHAR(255)
);

CREATE TABLE categories (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id BIGINT REFERENCES categories (id),
    name      VARCHAR(255) NOT NULL,
    slug      VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE product_types (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT       NOT NULL REFERENCES categories (id),
    name        VARCHAR(255) NOT NULL
);

CREATE TABLE products (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             VARCHAR(255) NOT NULL UNIQUE,
    name            VARCHAR(255) NOT NULL,
    brand_id        BIGINT       NOT NULL REFERENCES brands (id),
    category_id     BIGINT       NOT NULL REFERENCES categories (id),
    product_type_id BIGINT       NOT NULL REFERENCES product_types (id),
    description     TEXT,
    status          VARCHAR(255) NOT NULL,
    created_at      TIMESTAMPTZ  NOT NULL,
    updated_at      TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_products_category_id     ON products (category_id);
CREATE INDEX idx_products_product_type_id ON products (product_type_id);
CREATE INDEX idx_products_status          ON products (status);

CREATE TABLE parameter_groups (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE parameter_group_items (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(255) NOT NULL,
    parameter_group_id BIGINT       NOT NULL REFERENCES parameter_groups (id)
);

CREATE TABLE category_parameters (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(255) NOT NULL,
    code               VARCHAR(255),
    sort_order         INTEGER      NOT NULL,
    category_id        BIGINT       NOT NULL REFERENCES categories (id),
    parameter_type     VARCHAR(255) NOT NULL,
    int_value          INTEGER,
    double_value2      INTEGER,
    double_value3      INTEGER,
    boolean_value      BOOLEAN,
    string_value       VARCHAR(255),
    parameter_group_id BIGINT REFERENCES parameter_groups (id)
);

CREATE TABLE product_attributes (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id            BIGINT NOT NULL REFERENCES products (id),
    category_parameter_id BIGINT NOT NULL REFERENCES category_parameters (id),
    value                 TEXT   NOT NULL,
    UNIQUE (product_id, category_parameter_id)
);

CREATE TABLE component_groups (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL
);

CREATE TABLE components (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(255) NOT NULL,
    component_group_id BIGINT       NOT NULL REFERENCES component_groups (id)
);
