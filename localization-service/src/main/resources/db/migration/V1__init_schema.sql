CREATE TABLE languages (
    code    VARCHAR(255) PRIMARY KEY,
    name    VARCHAR(255) NOT NULL,
    enabled BOOLEAN      NOT NULL
);

CREATE TABLE translations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type      VARCHAR(255) NOT NULL,
    entity_id        BIGINT       NOT NULL,
    field_name       VARCHAR(255) NOT NULL,
    language_code    VARCHAR(255) NOT NULL REFERENCES languages (code),
    translated_value TEXT         NOT NULL,
    status           VARCHAR(255) NOT NULL,
    updated_at       TIMESTAMPTZ  NOT NULL,
    UNIQUE (entity_type, entity_id, field_name, language_code)
);

CREATE INDEX idx_translations_entity_type_entity_id ON translations (entity_type, entity_id);
CREATE INDEX idx_translations_language_code         ON translations (language_code);

CREATE TABLE translation_jobs (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type          VARCHAR(255) NOT NULL,
    entity_id            BIGINT       NOT NULL,
    target_language_code VARCHAR(255) NOT NULL REFERENCES languages (code),
    status               VARCHAR(255) NOT NULL,
    attempts             INTEGER      NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL,
    completed_at         TIMESTAMPTZ
);
