CREATE TABLE product_relations (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_product_id BIGINT       NOT NULL,
    target_product_id BIGINT       NOT NULL,
    relation_type     VARCHAR(255) NOT NULL,
    score             FLOAT8       NOT NULL,
    UNIQUE (source_product_id, target_product_id, relation_type)
);

CREATE INDEX idx_product_relations_source_id   ON product_relations (source_product_id);
CREATE INDEX idx_product_relations_source_type ON product_relations (source_product_id, relation_type);

CREATE TABLE recommendation_rules (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255) NOT NULL,
    strategy   VARCHAR(255) NOT NULL,
    parameters JSONB,
    priority   INTEGER      NOT NULL,
    enabled    BOOLEAN      NOT NULL
);

CREATE TABLE recommendation_snapshots (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id   BIGINT       NOT NULL,
    strategy     VARCHAR(255) NOT NULL,
    generated_at TIMESTAMPTZ  NOT NULL
);

CREATE INDEX idx_recommendation_snapshots_product_id       ON recommendation_snapshots (product_id);
CREATE INDEX idx_recommendation_snapshots_product_strategy ON recommendation_snapshots (product_id, strategy);

CREATE TABLE recommendation_snapshot_products (
    snapshot_id            BIGINT  NOT NULL REFERENCES recommendation_snapshots (id),
    recommended_product_id BIGINT  NOT NULL,
    position               INTEGER NOT NULL
);
